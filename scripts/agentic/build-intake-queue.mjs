#!/usr/bin/env node
/**
 * Build docs/workflow/plans/intake-queue.json from catalog + intake-scope.json + phase heuristics.
 */
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { discoverPhasesForEpic } from './phase-parse.mjs'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../..')
const CATALOG_INDEX = path.join(ROOT, '.agentic/catalog/index.json')
const CATALOG_TASKS = path.join(ROOT, '.agentic/catalog/tasks.json')
const DEFAULT_SCOPE = path.join(ROOT, 'docs/workflow/plans/intake-scope.json')
const OUT_QUEUE = path.join(ROOT, 'docs/workflow/plans/intake-queue.json')
const KANBAN_MIRROR = path.join(
  ROOT,
  'docs/reports/workflow/intake-queue.json',
)
const PLAN_ROOT = path.join(ROOT, 'docs/workflow/plans')

function rel(p) {
  return path.relative(ROOT, p).split(path.sep).join('/')
}

function parseArgs(argv) {
  const opts = { scopePath: DEFAULT_SCOPE, merge: false, refreshCatalog: false, allEpics: false }
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--scope' && argv[i + 1]) opts.scopePath = path.resolve(ROOT, argv[++i])
    else if (argv[i] === '--merge') opts.merge = true
    else if (argv[i] === '--catalog') opts.refreshCatalog = true
    else if (argv[i] === '--all') opts.allEpics = true
    else if (argv[i] === '--help' || argv[i] === '-h') {
      console.log(`Usage: node scripts/agentic/build-intake-queue.mjs [options]

  --scope <file>   Scope JSON (default: docs/workflow/plans/intake-scope.json)
  --merge          Keep planStatus/intakeStatus/kanbanColumn/released from existing queue
  --catalog        Run build-catalog.mjs first
  --all            Semua epic dari catalog (abaikan daftar epics di scope)
`)
      process.exit(0)
    }
  }
  return opts
}

function loadJson(filePath, label) {
  if (!fs.existsSync(filePath)) {
    console.error(`Missing ${label}: ${rel(filePath)}`)
    console.error('Run: npm run agentic:catalog')
    process.exit(1)
  }
  return JSON.parse(fs.readFileSync(filePath, 'utf8'))
}

function resolveDevPhasePath(epicMeta, scope) {
  const canonical = path.join(ROOT, epicMeta.devPhasePath)
  if (fs.existsSync(canonical)) return canonical
  if (scope.developmentPhasePaths?.length) {
    for (const p of scope.developmentPhasePaths) {
      const full = path.join(ROOT, p)
      if (p.includes(epicMeta.epic) && fs.existsSync(full)) return full
    }
  }
  return canonical
}

function planStatusFor(ordinal, priorReleased, intakeComplete) {
  if (ordinal > 1 && !priorReleased) return 'blocked'
  if (!intakeComplete) return 'blocked'
  return 'ready_for_plan'
}

function writeIntakeSummary(epic, phaseNn, phaseRow) {
  const dir = path.join(PLAN_ROOT, epic, `phase-${phaseNn}`)
  fs.mkdirSync(dir, { recursive: true })
  const lines = [
    `# Intake summary — ${phaseRow.phaseId}`,
    '',
    `| Field | Nilai |`,
    `|-------|-------|`,
    `| Epic | ${epic} |`,
    `| Phase | ${phaseRow.title} |`,
    `| Gate | ${phaseRow.gate || '—'} |`,
    `| Task count | ${phaseRow.taskIds.length} |`,
    '',
    '## Task IDs',
    '',
    ...phaseRow.taskIds.map((id) => `- \`${id}\``),
    '',
    'Generated by `npm run agentic:intake-queue`.',
    '',
  ]
  fs.writeFileSync(path.join(dir, 'intake-summary.md'), lines.join('\n'))
}

function main() {
  const opts = parseArgs(process.argv)
  if (opts.refreshCatalog) {
    const r = spawnSync('node', ['scripts/agentic/build-catalog.mjs'], { cwd: ROOT, stdio: 'inherit' })
    if (r.status !== 0) process.exit(r.status ?? 1)
  }

  const scope = loadJson(opts.scopePath, 'intake-scope')
  const index = loadJson(CATALOG_INDEX, 'catalog index')
  const allTasks = loadJson(CATALOG_TASKS, 'catalog tasks')

  let epicIds = index.epics.map((e) => e.epic)
  if (!opts.allEpics && scope.scope?.epics?.length) {
    const raw = scope.scope.epics
    epicIds = raw.includes('all') || raw[0] === 'all' ? epicIds : raw
  }

  const epicMetaById = new Map(index.epics.map((e) => [e.epic, e]))
  let previous = {}
  if (opts.merge && fs.existsSync(OUT_QUEUE)) {
    try {
      previous = loadJson(OUT_QUEUE, 'existing queue').phases || {}
    } catch {
      previous = {}
    }
  }

  /** @type {Record<string, object>} */
  const prevByPhaseId = {}
  if (Array.isArray(previous)) {
    for (const p of previous) prevByPhaseId[p.phaseId] = p
  } else if (previous && typeof previous === 'object') {
    Object.assign(prevByPhaseId, previous)
  }

  const scopePhases = []
  const warnings = []

  for (const epic of epicIds) {
    const meta = epicMetaById.get(epic)
    if (!meta) {
      warnings.push(`Epic ${epic} tidak ada di catalog`)
      continue
    }
    const tasks = allTasks.filter((t) => t.epic === epic)
    const devPath = resolveDevPhasePath(meta, scope.scope || {})
    if (!fs.existsSync(devPath)) {
      warnings.push(`Development phase hilang: ${rel(devPath)}`)
      continue
    }
    const epicConfig = scope.epicConfig?.[epic] || {}
    const discovered = discoverPhasesForEpic(devPath, tasks, { epic, splits: epicConfig.splits })

    const assigned = new Set()
    for (const ph of discovered) {
      for (const id of ph.taskIds) assigned.add(id)
    }
    const orphans = tasks.map((t) => t.id).filter((id) => !assigned.has(id))
    if (orphans.length && discovered.length) {
      discovered[discovered.length - 1].taskIds.push(...orphans)
    } else if (orphans.length && !discovered.length) {
      discovered.push({
        phaseNum: 1,
        title: `Epic ${epic} — seluruh task`,
        taskIds: orphans,
      })
    }

    for (const ph of discovered) {
      const phaseNn = String(ph.phaseNum).padStart(2, '0')
      const phaseId = ph.phaseId || `${epic}-P${ph.phaseNum}`
      if (!ph.taskIds.length) {
        warnings.push(`${phaseId}: tidak ada task — periksa splits atau parse phase`)
      }
      const prev = prevByPhaseId[phaseId] || {}
      const intakeStatus = prev.intakeStatus || 'queued'
      const intakeComplete = prev.intakeComplete ?? intakeStatus === 'intake_complete'
      const released = prev.released ?? false
      const ordinal = ph.phaseNum
      const prior = scopePhases.filter((p) => p.epic === epic).sort((a, b) => a.ordinal - b.ordinal)
      const priorReleased = ordinal === 1 ? true : prior.length ? prior[prior.length - 1].released : false
      let planStatus = prev.planStatus
      if (!opts.merge || !planStatus) {
        planStatus = planStatusFor(ordinal, priorReleased, intakeComplete)
      }

      const row = {
        phaseId,
        epic,
        ordinal,
        title: ph.title,
        gate: ph.gate || meta.gate,
        devPhasePath: meta.devPhasePath,
        prdFolder: meta.prdFolder,
        taskIds: ph.taskIds,
        taskCount: ph.taskIds.length,
        agenticReadyCount: ph.taskIds.filter((id) => tasks.find((t) => t.id === id)?.agenticReady).length,
        intakeStatus,
        intakeComplete,
        planStatus,
        released,
        intakeSubStep: prev.intakeSubStep || (intakeComplete ? 'plan' : 'queue'),
        kanbanColumn:
          prev.kanbanColumn ||
          (prev.planStatus === 'plan_complete'
            ? 'development'
            : intakeComplete || prev.intakeSubStep === 'plan'
              ? 'plan'
              : 'intake'),
        currentTaskId: prev.currentTaskId ?? null,
        planTaskDone: prev.planTaskDone ?? 0,
      }
      scopePhases.push(row)
      writeIntakeSummary(epic, phaseNn, row)
    }
  }

  scopePhases.sort((a, b) => a.epic.localeCompare(b.epic) || a.ordinal - b.ordinal)

  const out = {
    version: 1,
    generatedAt: new Date().toISOString(),
    instructedBy: scope.instructedBy || 'human',
    scope: {
      ...scope.scope,
      epics: epicIds,
    },
    gates: scope.gates || { planRequiresPriorPhaseHumanQa: true },
    phases: scopePhases,
    warnings,
  }

  fs.mkdirSync(PLAN_ROOT, { recursive: true })
  const payload = JSON.stringify(out, null, 2) + '\n'
  fs.writeFileSync(OUT_QUEUE, payload)
  fs.mkdirSync(path.dirname(KANBAN_MIRROR), { recursive: true })
  fs.writeFileSync(KANBAN_MIRROR, payload)

  console.log(`Intake queue: ${scopePhases.length} phase(s) → ${rel(OUT_QUEUE)}`)
  console.log(`  Kanban mirror: ${rel(KANBAN_MIRROR)}`)
  for (const p of scopePhases) {
    console.log(`  ${p.phaseId}: ${p.taskCount} task (${p.planStatus})`)
  }
  if (warnings.length) {
    console.warn('Warnings:')
    for (const w of warnings) console.warn(`  - ${w}`)
  }
}

main()
